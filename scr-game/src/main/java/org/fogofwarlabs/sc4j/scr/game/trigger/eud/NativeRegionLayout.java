    /**
     * Aligns an address up to the alignment of allocated regions, as the region allocator places the next region.
     *
     * @param address a classic address
     * @return the address rounded up to a multiple of the region alignment
     */
    public static int alignAddress(int address) {
        return address + REGION_ALIGNMENT - 1 & -REGION_ALIGNMENT;
    }

    /**
     * Tells whether a region below {@link #MAP_REGION_BASE} serves an address.
     *
     * @param address a classic address
     * @return {@code true} if a region below {@link #MAP_REGION_BASE} serves the address, {@code false} otherwise
     */
    public static boolean isMapped(int address) {
        long target = address & DWORD_MASK;
        int low = 0;
        int high = INTERVALS.length / REGION_ROW_SIZE - 1;

        while (low <= high) {
            int middle = (low + high) >>> 1;
            long start = INTERVALS[middle * REGION_ROW_SIZE] & DWORD_MASK;
            long end = INTERVALS[middle * REGION_ROW_SIZE + 1] & DWORD_MASK;

            if (target < start) {
                high = middle - 1;
            } else if (target >= end) {
                low = middle + 1;
            } else {
                return true;
            }
        }

        return false;
    }

    /**
     * Tells whether an address below the map-dependent range is outside the intervals.
     *
     * @param address a classic address
     * @return {@code true} if the address is below {@link #MAP_REGION_BASE} and no region serves it, {@code false}
     * otherwise
     */
    public static boolean isUnmapped(int address) {
        return Integer.compareUnsigned(address, MAP_REGION_BASE) < 0 && !isMapped(address);
    }

    /**
     * Tells whether no region below {@link #MAP_REGION_BASE} serves a byte of a range that ends at or below it.
     *
     * @param base the classic address of the range
     * @param size the size of the range in bytes
     * @return {@code true} if the range ends at or below {@link #MAP_REGION_BASE} and no interval overlaps it, {@code false} otherwise
     */
    public static boolean isRangeUnmapped(int base, int size) {
        long start = base & DWORD_MASK;
        long end = start + size;

        if (end > (MAP_REGION_BASE & DWORD_MASK)) {
            return false;
        }

        for (int index = 0; index < INTERVALS.length; index += REGION_ROW_SIZE) {
            if ((INTERVALS[index] & DWORD_MASK) < end && (INTERVALS[index + 1] & DWORD_MASK) > start) {
                return false;
            }
        }

        return true;
    }

